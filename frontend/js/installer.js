// js/installer.js
import { deployOrchestrationPackage } from './services/api.js';

const Installer = {
  init: function() {
    // Prevent duplicate injections
    if (document.getElementById('installModal')) return;

    const modalHTML = `
      <div id="installModal" class="hidden absolute inset-0 bg-slate-900/40 backdrop-blur-sm z-50 flex items-center justify-center transition-opacity">
        <div class="bg-white rounded-2xl shadow-2xl w-full max-w-lg flex flex-col border border-slate-200 overflow-hidden transform transition-all">
          <div class="px-6 py-5 border-b border-slate-100 flex justify-between items-center bg-slate-50/50">
            <h3 class="text-lg font-bold text-slate-800 tracking-tight flex items-center gap-2">
              <svg class="w-5 h-5 text-indigo-500" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 11H5m14 0a2 2 0 012 2v6a2 2 0 01-2 2H5a2 2 0 01-2-2v-6a2 2 0 012-2m14 0V9a2 2 0 00-2-2M5 11V9a2 2 0 012-2m0 0V5a2 2 0 012-2h6a2 2 0 012 2v2M7 7h10"></path></svg>
              Deploy AI Package
            </h3>
            <button id="closeInstallerTopBtn" class="text-slate-400 hover:text-slate-600 bg-white hover:bg-slate-100 p-1 rounded-md transition-colors">
              <svg class="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M6 18L18 6M6 6l12 12"></path></svg>
            </button>
          </div>
          <div class="p-8">
            <p class="text-sm text-slate-500 mb-6">Upload the <code class="bg-slate-100 text-indigo-600 px-1 py-0.5 rounded">.json</code> manifest file generated by the AI to instantly provision objects, workflows, and permissions.</p>
            
            <div class="flex items-center justify-center w-full">
              <label for="jsonFileInput" class="flex flex-col items-center justify-center w-full h-36 border-2 border-slate-300 border-dashed rounded-xl cursor-pointer bg-slate-50 hover:bg-indigo-50 hover:border-indigo-300 transition-colors group">
                <div class="flex flex-col items-center justify-center pt-5 pb-6">
                  <svg class="w-10 h-10 mb-3 text-slate-400 group-hover:text-indigo-500 transition-colors" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="1.5" d="M7 16a4 4 0 01-.88-7.903A5 5 0 1115.9 6L16 6a5 5 0 011 9.9M15 13l-3-3m0 0l-3 3m3-3v12"></path></svg>
                  <p class="mb-2 text-sm text-slate-600"><span class="font-bold text-indigo-600">Click to upload</span> or drag and drop</p>
                  <p class="text-[11px] font-medium text-slate-400 uppercase tracking-wider">JSON files only</p>
                </div>
                <input id="jsonFileInput" type="file" accept=".json" class="hidden" />
              </label>
            </div>

            <div id="fileNameDisplay" class="hidden mt-4 p-3 bg-indigo-50 rounded-lg items-center gap-2 border border-indigo-100">
              <svg class="w-4 h-4 text-indigo-500" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z"></path></svg>
              <span id="fileNameText" class="text-sm text-indigo-700 font-medium"></span>
            </div>

            <p id="installError" class="text-rose-500 text-sm mt-3 hidden bg-rose-50 p-3 rounded-lg border border-rose-100"></p>
          </div>
          <div class="px-6 py-4 border-t border-slate-100 bg-slate-50/50 flex justify-end gap-3">
            <button id="closeInstallerBottomBtn" class="px-5 py-2.5 text-sm font-semibold text-slate-600 hover:bg-slate-200 rounded-lg transition-colors">Cancel</button>
            <button id="deployBtn" class="px-5 py-2.5 text-sm font-semibold text-white bg-gradient-to-r from-indigo-600 to-violet-600 hover:from-indigo-700 hover:to-violet-700 rounded-lg shadow-md hover:shadow-lg hover:shadow-indigo-500/30 transition-all flex items-center gap-2">
              Deploy Engine
            </button>
          </div>
        </div>
      </div>
    `;
    document.body.insertAdjacentHTML('beforeend', modalHTML);

    // Bind Event Listeners (The ES Module Way)
    document.getElementById('closeInstallerTopBtn').addEventListener('click', Installer.toggleModal);
    document.getElementById('closeInstallerBottomBtn').addEventListener('click', Installer.toggleModal);
    document.getElementById('jsonFileInput').addEventListener('change', Installer.updateFileName);
    document.getElementById('deployBtn').addEventListener('click', Installer.deployPackage);
  },

  toggleModal: function() {
    const modal = document.getElementById('installModal');
    modal.classList.toggle('hidden');
    document.getElementById('installError').classList.add('hidden');

    const display = document.getElementById('fileNameDisplay');
    display.classList.add('hidden');
    display.classList.remove('flex');
    document.getElementById('jsonFileInput').value = '';
  },

  updateFileName: function() {
    const input = document.getElementById('jsonFileInput');
    const display = document.getElementById('fileNameDisplay');
    const text = document.getElementById('fileNameText');

    if (input.files.length > 0) {
      text.innerText = input.files[0].name;
      display.classList.remove('hidden');
      display.classList.add('flex');
      document.getElementById('installError').classList.add('hidden');
    } else {
      display.classList.add('hidden');
      display.classList.remove('flex');
    }
  },

  deployPackage: async function() {
    const btn = document.getElementById('deployBtn');
    const errorText = document.getElementById('installError');
    const fileInput = document.getElementById('jsonFileInput');

    errorText.classList.add('hidden');

    if (fileInput.files.length === 0) {
      errorText.innerText = "Please select a JSON file to upload.";
      errorText.classList.remove('hidden');
      return;
    }

    let jsonPayload;
    try {
      const text = await fileInput.files[0].text();
      jsonPayload = JSON.parse(text);
    } catch (e) {
      errorText.innerText = "Invalid JSON syntax. Ensure it is correctly formatted.";
      errorText.classList.remove('hidden');
      return;
    }

    const originalBtnHTML = btn.innerHTML;
    btn.innerHTML = `<svg class="animate-spin h-4 w-4 text-white" xmlns="http://w3.org" fill="none" viewBox="0 0 24 24"><circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle><path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path></svg> Deploying...`;
    btn.disabled = true;

    try {
      // Call the centralized API function
      await deployOrchestrationPackage(jsonPayload);

      Installer.toggleModal();
      // Trigger UI refresh
      if (typeof window.loadSidebar === "function") window.loadSidebar();

    } catch (error) {
      errorText.innerText = `Deployment Error: ${error.message}`;
      errorText.classList.remove('hidden');
    } finally {
      btn.innerHTML = originalBtnHTML;
      btn.disabled = false;
    }
  }
};

// Initialize the modal injection
Installer.init();

// Expose the toggle function to the window so your top navigation bar can still open the modal
window.toggleInstallModal = Installer.toggleModal;
